#!/usr/bin/env python3
"""Encode the reviewed long low defeat meow; keep the source and WAVs local."""
import array
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import wave

root=Path(__file__).resolve().parents[1]
cut=json.loads((root/'audio/recorded/rainbow-cat-defeat.json').read_text())
source=Path(sys.argv[1])
if hashlib.sha256(source.read_bytes()).hexdigest()!=cut['source_sha256']:
    raise SystemExit('Source does not match reviewed defeat recording')
env=os.environ.copy()
if Path('/data/data/com.termux/files/usr/lib').exists():env.pop('LD_LIBRARY_PATH',None)
duration=cut['end']-cut['start']
filters=(f"atrim=start={cut['start']}:end={cut['end']},asetpts=PTS-STARTPTS,"
         f"afade=t=in:d=0.003,afade=t=out:st={duration-.035:.6f}:d=0.035")
raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-af',filters,
    '-ac','1','-ar','22050','-f','s16le','-'],env=env)
pcm=array.array('h',raw)
if sys.byteorder!='little':pcm.byteswap()
pcm[0]=pcm[-1]=0
peak=max(map(abs,pcm));rms=math.sqrt(sum(v*v for v in pcm)/len(pcm))
assert 32<peak<32767 and rms>1 and abs(len(pcm)/22050-duration)<.003
encoded=''.join(f'{v & 65535:04x}' for v in pcm)
java='''package com.dddumpling.game;

/** Generated by tools/prepare-cat-defeat.py; provenance: audio/recorded/rainbow-cat-defeat.json. */
final class CatDefeatRecording {
    private CatDefeatRecording() {}
'''
java+=f'    static final float DURATION={len(pcm)/22050:.6f}f;\n'
java+='''    static short[] build() {
        int count=0;for(String chunk:PCM)count+=chunk.length()/4;
        short[] pcm=new short[count];int at=0;
        for(String chunk:PCM)for(int i=0;i<chunk.length();i+=4)
            pcm[at++]=(short)Integer.parseInt(chunk.substring(i,i+4),16);
        return pcm;
    }
    private static final String[] PCM={
'''
java+=''.join('        "'+encoded[i:i+4000]+'",\n' for i in range(0,len(encoded),4000))+'    };\n}\n'
(root/'src/com/dddumpling/game/CatDefeatRecording.java').write_text(java)
out=root/'build/cat-defeat/game';out.mkdir(parents=True,exist_ok=True)
if sys.byteorder!='little':pcm.byteswap()
with wave.open(str(out/'meow-long-low.wav'),'wb') as wav:
    wav.setparams((1,2,22050,0,'NONE','none'));wav.writeframes(pcm.tobytes())
print(f'{len(pcm)/22050:.3f}s peak={20*math.log10(peak/32768):.2f}dBFS RMS={20*math.log10(rms/32768):.2f}dBFS; silent endpoints, original level and pitch')
