#!/usr/bin/env python3
"""Rebuild Rainbow Cat's recorded PCM bank from the user's annotated recording."""
import array
import hashlib
import json
import math
import os
from pathlib import Path
import shutil
import subprocess
import sys
import wave

root=Path(__file__).resolve().parents[1]
source=Path(sys.argv[1])
manifest=json.loads((root/'audio/recorded/rainbow-cat-cuts.json').read_text())
if hashlib.sha256(source.read_bytes()).hexdigest()!=manifest['source_sha256']:
    raise SystemExit('Source does not match reviewed recording')
env=os.environ.copy()
if Path('/data/data/com.termux/files/usr/lib').exists():env.pop('LD_LIBRARY_PATH',None)
ffmpeg=shutil.which('ffmpeg') or '/data/data/com.termux/files/usr/bin/ffmpeg'
out=root/'build/cat-meows/game';out.mkdir(parents=True,exist_ok=True)
# Remove exports no longer present in the reviewed bank.
retained={cut['name']+'.wav' for cut in manifest['clips']}
for stale in out.glob('*.wav'):
    if stale.name not in retained:stale.unlink()
chunks=[];durations=[]
for cut in manifest['clips']:
    start,end=cut['start'],cut['end'];duration=end-start
    filters=(f'atrim=start={start}:end={end},asetpts=PTS-STARTPTS,'
             f'afade=t=in:d=0.003,afade=t=out:st={duration-.020:.6f}:d=0.020')
    raw=subprocess.check_output([ffmpeg,'-v','error','-i',str(source),'-map','0:a:0',
        '-af',filters,'-ac','1','-ar','22050','-f','s16le','-'],env=env)
    pcm=array.array('h',raw)
    if sys.byteorder!='little':pcm.byteswap()
    pcm[0]=pcm[-1]=0
    peak=max(map(abs,pcm));rms=math.sqrt(sum(v*v for v in pcm)/len(pcm))
    assert 32<peak<32767 and rms>1 and abs(len(pcm)/22050-duration)<.003
    durations.append(len(pcm)/22050)
    chunks.append(''.join(f'{v & 65535:04x}' for v in pcm))
    if sys.byteorder!='little':pcm.byteswap()
    with wave.open(str(out/(cut['name']+'.wav')),'wb') as wav:
        wav.setparams((1,2,22050,0,'NONE','none'));wav.writeframes(pcm.tobytes())
    print(f"{cut['name']}: {duration:.3f}s peak={peak} RMS={rms:.1f}")
java='''package com.dddumpling.game;

/** Generated by tools/prepare-cat-meows.py; source/cuts: audio/recorded/rainbow-cat-cuts.json. */
final class CatMeowRecording {
    static final int SHORT_COUNT=21, STRUGGLE=21, HURT=22, SURPRISED=23, DEFEAT=24, COUNT=25;
    private CatMeowRecording() {}
    static float duration(int variant) {return variant==DEFEAT?CatDefeatRecording.DURATION:DURATIONS[variant];}
    static short[] build(int variant) {
        if(variant==DEFEAT)return CatDefeatRecording.build();
        String[] chunks=PCM[variant];int length=0;
        for(String chunk:chunks)length+=chunk.length()/4;
        short[] pcm=new short[length];int at=0;
        for(String chunk:chunks)for(int i=0;i<chunk.length();i+=4)
            pcm[at++]=(short)Integer.parseInt(chunk.substring(i,i+4),16);
        return pcm;
    }
'''
java+='    private static final float[] DURATIONS={'+','.join(f'{v:.6f}f' for v in durations)+'};\n'
java+='    private static final String[][] PCM={\n'
for data in chunks:java+='        {\n'+''.join('            "'+data[i:i+4000]+'",\n' for i in range(0,len(data),4000))+'        },\n'
java+='    };\n}\n'
(root/'src/com/dddumpling/game/CatMeowRecording.java').write_text(java)
