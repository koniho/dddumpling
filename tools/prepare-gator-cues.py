#!/usr/bin/env python3
"""Embed three user prompt takes and the CC0 splash. Originals remain outside source control."""
import array
import hashlib
import os
from pathlib import Path
import subprocess
import sys
import wave

root = Path(__file__).resolve().parents[1]
rate = 22050
env = os.environ.copy()
termux = Path('/data/data/com.termux/files/usr/lib')
if termux.exists():
    env['LD_LIBRARY_PATH'] = str(termux)

def decode(path):
    raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(path),
        '-map', '0:a:0', '-af', 'lowpass=f=4000:p=2',
        '-ac', '1', '-ar', str(rate), '-f', 's16le', '-'], env=env)
    samples = array.array('h', raw)
    if sys.byteorder != 'little':
        samples.byteswap()
    print(f'{path.name}: SHA-256 {hashlib.sha256(path.read_bytes()).hexdigest()}')
    return samples

prompt = decode(Path(sys.argv[1]))
splash = decode(Path(sys.argv[2]))
# Small margins around the three measured vocal onsets/ends preserve their articulation.
takes = [list(prompt[round(start*rate):round(end*rate)])
         for start, end in [(1.505, 1.730), (2.192, 2.430), (2.977, 3.225)]]
takes.append(list(splash))
java = '''package com.dddumpling.game;

/** Generated by tools/prepare-gator-cues.py; recording provenance: audio/recorded/README.md. */
final class GatorCueRecording {
    private GatorCueRecording() {}
    static short[] build(int variant) {
        String[] chunks = PCM[variant];
        int length = 0;
        for (String chunk : chunks) length += chunk.length()/4;
        short[] pcm = new short[length];
        int at = 0;
        for (String chunk : chunks)
            for (int i = 0; i < chunk.length(); i += 4)
                pcm[at++] = (short)Integer.parseInt(chunk.substring(i, i+4), 16);
        return pcm;
    }
    private static final String[][] PCM = {
'''
for index, values in enumerate(takes):
    tail = .045 if index == 3 else .012
    for i in range(len(values)):
        values[i] *= min(1, i/(.002*rate), (len(values)-1-i)/(tail*rate))
    gain = .85*32767/max(map(abs, values))
    pcm = array.array('h', (round(v*gain) for v in values))
    hexed = ''.join(f'{v & 65535:04x}' for v in pcm)
    java += '        {\n' + ''.join('            "'+hexed[i:i+4000]+'",\n'
                                   for i in range(0,len(hexed),4000)) + '        },\n'
    if sys.byteorder != 'little':
        pcm.byteswap()
    output = root/'build'/('gator-splash.wav' if index == 3 else f'gator-prompt-{index+1}.wav')
    output.parent.mkdir(exist_ok=True)
    with wave.open(str(output), 'wb') as wav:
        wav.setparams((1, 2, rate, 0, 'NONE', 'none'))
        wav.writeframes(pcm.tobytes())
    print(f'{output.name}: {len(pcm)/rate:.3f}s')
java += '    };\n}\n'
(root/'src/com/dddumpling/game/GatorCueRecording.java').write_text(java)
