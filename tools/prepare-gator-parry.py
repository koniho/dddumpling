#!/usr/bin/env python3
"""Trim the user's Thud recording and embed identical PCM for both native hosts."""
import array
import hashlib
import os
from pathlib import Path
import subprocess
import sys
import wave

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
env = os.environ.copy()
termux = Path('/data/data/com.termux/files/usr/lib')
if termux.exists():
    env['LD_LIBRARY_PATH'] = str(termux)
raw = subprocess.check_output([
    'ffmpeg', '-v', 'error', '-i', str(source), '-map', '0:a:0',
    '-ac', '1', '-ar', '22050', '-f', 's16le', '-'
], env=env)
samples = array.array('h', raw)
if sys.byteorder != 'little':
    samples.byteswap()
rate = 22050
# Measured impact is .697-.952s; retain a little lead and the natural quiet tail.
values = list(samples[round(.685 * rate):round(1.015 * rate)])
for i in range(len(values)):
    values[i] *= min(1, i / (.002 * rate), (len(values)-1-i) / (.015 * rate))
gain = .85 * 32767 / max(map(abs, values))
pcm = array.array('h', (round(v * gain) for v in values))
hexed = ''.join(f'{v & 65535:04x}' for v in pcm)
java = '''package com.dddumpling.game;

/** User recording. Generated by tools/prepare-gator-parry.py; see audio/recorded/README.md. */
final class GatorParryRecording {
    private GatorParryRecording() {}
    static short[] build() {
        short[] pcm = new short[%d];
        int at = 0;
        for (String chunk : PCM)
            for (int i = 0; i < chunk.length(); i += 4)
                pcm[at++] = (short) Integer.parseInt(chunk.substring(i, i + 4), 16);
        return pcm;
    }
    private static final String[] PCM = {
''' % len(pcm)
java += ''.join('        "' + hexed[i:i+4000] + '",\n' for i in range(0,len(hexed),4000))
java += '    };\n}\n'
(root/'src/com/dddumpling/game/GatorParryRecording.java').write_text(java)
output = root/'build/gator-parry.wav'
output.parent.mkdir(exist_ok=True)
if sys.byteorder != 'little':
    pcm.byteswap()
with wave.open(str(output), 'wb') as wav:
    wav.setparams((1, 2, rate, 0, 'NONE', 'none'))
    wav.writeframes(pcm.tobytes())
print(f'Gator parry: {len(pcm)/rate:.3f}s; source SHA-256 {hashlib.sha256(source.read_bytes()).hexdigest()}')
