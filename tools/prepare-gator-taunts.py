#!/usr/bin/env python3
"""Split the user's two three-growl performances; retain spacing and bake mouth envelopes."""
import array
import hashlib
import math
import os
from pathlib import Path
import subprocess
import sys
import wave

root = Path(__file__).resolve().parents[1]
rate = 22050
env = os.environ.copy()
if Path('/data/data/com.termux/files/usr/lib').exists():
    env['LD_LIBRARY_PATH'] = '/data/data/com.termux/files/usr/lib'
# Breath valleys separate three growls; retain the quiet articulation inside the final long growl.
cuts = [[(.845, 1.105), (1.150, 1.440), (1.480, 2.145)],
        [(1.010, 1.230), (1.305, 1.525), (1.635, 1.860)]]
pcms, envelopes, offsets, durations = [], [], [], []
for phase, source in enumerate(map(Path, sys.argv[1:3])):
    raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source),
        '-af', 'lowpass=f=4000:p=2', '-ac', '1', '-ar', str(rate), '-f', 's16le', '-'], env=env)
    samples = array.array('h', raw)
    if sys.byteorder != 'little': samples.byteswap()
    print(f'{source.name}: SHA-256 {hashlib.sha256(source.read_bytes()).hexdigest()}')
    offsets.append([start-cuts[phase][0][0] for start, end in cuts[phase]])
    for growl, (start, end) in enumerate(cuts[phase]):
        values = list(samples[round(start*rate):round(end*rate)])
        for i in range(len(values)):
            values[i] *= min(1, i/(.003*rate), (len(values)-1-i)/(.015*rate))
        gain = .85*32767/max(map(abs, values))
        pcm = array.array('h', (round(v*gain) for v in values))
        durations.append(len(pcm)/rate)
        # Smoothed 10ms RMS animation follows the recorded voice, not an unrelated sine wave.
        rms = []
        for frame in range(math.ceil(len(pcm)/(rate*.01))+1):
            at = round(frame*.01*rate)
            segment = pcm[max(0,at-round(.015*rate)):min(len(pcm),at+round(.015*rate))]
            rms.append(math.sqrt(sum(v*v for v in segment)/max(1,len(segment))))
        peak = max(rms)
        envelope = [min(1, (v/peak)**.65) for v in rms]
        envelope[0] = envelope[-1] = 0
        envelopes.append(envelope)
        pcms.append(''.join(f'{v & 65535:04x}' for v in pcm))
        output = root/'build'/f'gator-taunt-{phase+1}-{growl+1}.wav'
        if sys.byteorder != 'little': pcm.byteswap()
        with wave.open(str(output), 'wb') as wav:
            wav.setparams((1,2,rate,0,'NONE','none'));wav.writeframes(pcm.tobytes())
        print(f'{output.name}: onset {offsets[-1][growl]:.3f}s, duration {durations[-1]:.3f}s')

def floats(values): return ','.join(f'{v:.5f}f' for v in values)
java = '''package com.dddumpling.game;

/** Generated by tools/prepare-gator-taunts.py; source and cuts: audio/recorded/README.md. */
final class GatorTauntRecording {
    static final float LEAD=.12f;
    private GatorTauntRecording() {}
    static float onset(int phase,int growl) {return LEAD+OFFSETS[phase][growl];}
    static float end(int phase) {return onset(phase,2)+DURATIONS[phase*3+2];}
    static float mouth(int phase,float age) {
        for(int growl=0;growl<3;growl++) {
            int id=phase*3+growl;
            float t=age-onset(phase,growl);
            if(t<=0 || t>=DURATIONS[id])continue;
            float frame=t*100;
            int index=(int)frame;
            float[] envelope=ENVELOPES[id];
            if(index+1>=envelope.length)return 0;
            return envelope[index]+(envelope[index+1]-envelope[index])*(frame-index);
        }
        return 0;
    }
    static short[] build(int variant) {
        String[] chunks=PCM[variant];int length=0;
        for(String chunk:chunks)length+=chunk.length()/4;
        short[] pcm=new short[length];int at=0;
        for(String chunk:chunks)for(int i=0;i<chunk.length();i+=4)
            pcm[at++]=(short)Integer.parseInt(chunk.substring(i,i+4),16);
        return pcm;
    }
'''
java += '    private static final float[] DURATIONS={'+floats(durations)+'};\n'
for name, values in [('OFFSETS', offsets), ('ENVELOPES', envelopes)]:
    java += '    private static final float[][] '+name+'={\n'
    java += ''.join('        {'+floats(v)+'},\n' for v in values)+'    };\n'
java += '    private static final String[][] PCM={\n'
for hexed in pcms:
    java += '        {\n'+''.join('            "'+hexed[i:i+4000]+'",\n' for i in range(0,len(hexed),4000))+'        },\n'
java += '    };\n}\n'
(root/'src/com/dddumpling/game/GatorTauntRecording.java').write_text(java)
