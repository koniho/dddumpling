#!/usr/bin/env python3
"""Bake impact-aligned, pitched squishes with a soft cartoon boip and 4 kHz low-pass."""
import array
import hashlib
import math
import os
from pathlib import Path
import subprocess
import sys
import wave

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
expected = '208290c9f76b0499698433c71774cac6e6411ea59cae76983a69b8b86cc48847'
if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
    raise SystemExit('Source differs from the reviewed Squish .m4a recording')
# Audited attacks; the heavy takes end before their second squeeze.
cuts = [(0.82,1.19),(1.48,1.84),(3.10,3.58),(4.43,5.05),(6.10,6.36),(7.98,8.16)]
pitch_rate = round(48000 * 2 ** (7 / 12))  # Seven semitones up, with a shorter tail.
env = os.environ.copy()
if env.get('PREFIX', '').startswith('/data/data/com.termux/'):
    env.pop('LD_LIBRARY_PATH', None)
output = root/'build/slime-squishes'; output.mkdir(parents=True, exist_ok=True)
pcms = []
for index, (start,end) in enumerate(cuts):
    duration = (end-start)*48000/pitch_rate
    # Reset timestamps before the clip-relative fades; retain the original intensity ladder.
    filters = (f'atrim=start={start}:end={end},asetpts=PTS-STARTPTS,'
               f'aformat=channel_layouts=mono,aresample=48000,asetrate={pitch_rate},aresample=48000,afade=t=in:d=0.003,'
               f'afade=t=out:st={duration-.02:.6f}:d=0.02,lowpass=f=4000:p=2,aresample=22050')
    raw = subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-map','0:a:0',
        '-af',filters,'-f','s16le','-'],env=env)
    pcm = array.array('h',raw)
    if sys.byteorder != 'little': pcm.byteswap()
    # One common +6 dB adjustment brings the quiet recording into the game's effects mix.
    shaped = []
    # A short, rounded falling bubble adds a playful attack without a sharp click.
    # One decaying attack, with a rubbery pitch wobble but no second beat.
    phase = 0.0
    for frame, sample in enumerate(pcm):
        t = frame/22050
        frequency = 210 + (800-index*30)*math.exp(-t/.04)
        frequency += 65*math.sin(2*math.pi*18*t)*math.exp(-t/.07)
        phase += 2*math.pi*frequency/22050
        envelope = min(1,t/.002)*math.exp(-t/.045)*min(1,(duration-t)/.015)
        boip = (2500+index*250)*envelope*(math.sin(phase)+.18*math.sin(phase*2))
        shaped.append(round(sample*2+boip))
    pcm = array.array('h',shaped)
    pcm[0] = pcm[-1] = 0
    peak = max(map(abs,pcm))
    assert 100 < peak < 32767 and abs(len(pcm)/22050-duration)<.003
    pcms.append(''.join(f'{v & 65535:04x}' for v in pcm))
    if sys.byteorder != 'little': pcm.byteswap()
    path=output/f'slime-squish-{index+1:02d}.wav'
    with wave.open(str(path),'wb') as wav:
        wav.setparams((1,2,22050,0,'NONE','none')); wav.writeframes(pcm.tobytes())
    print(f'{path.name}: {duration:.2f}s, peak {peak}/32767')
java = '''package com.dddumpling.game;

/** Generated by tools/prepare-slime-squishes.py; provenance: audio/recorded/README.md. */
final class SlimeSquishRecording {
    private SlimeSquishRecording() {}
    static short[] build(int variant) {
        String[] chunks=PCM[Math.max(0,Math.min(5,variant))];int length=0;
        for(String chunk:chunks)length+=chunk.length()/4;
        short[] pcm=new short[length];int at=0;
        for(String chunk:chunks)for(int i=0;i<chunk.length();i+=4)
            pcm[at++]=(short)Integer.parseInt(chunk.substring(i,i+4),16);
        return pcm;
    }
    private static final String[][] PCM={
'''
for hexed in pcms:
    java += '        {\n'+''.join('            "'+hexed[i:i+4000]+'",\n' for i in range(0,len(hexed),4000))+'        },\n'
java += '    };\n}\n'
(root/'src/com/dddumpling/game/SlimeSquishRecording.java').write_text(java)
