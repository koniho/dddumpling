#!/usr/bin/env python3
"""Embed Facecam's CC BY 4.0 Yay recreation. See assets/AudioCredits.txt."""
from pathlib import Path
import hashlib
import struct
import subprocess
import sys
import wave

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
expected = '6bfc349b66457855cd7f05cad5b897989d738e936103b5a19dffa08346ba7c43'
if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
    raise SystemExit('Unexpected source hash; review provenance before importing.')
data = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source),
    '-ac', '1', '-ar', '22050', '-f', 's16le', '-'])
values = [v for (v,) in struct.iter_unpack('<h', data)]
for i in range(len(values)):
    values[i] *= max(0, min(1, i / (22050 * .005), (len(values)-1-i) / (22050 * .035)))
gain = .85 * 32767 / max(map(abs, values))
pcm = [round(v * gain) for v in values]
out = root / 'out/sfx/survival-cheer.wav'
out.parent.mkdir(parents=True, exist_ok=True)
with wave.open(str(out), 'wb') as w:
    w.setparams((1, 2, 22050, 0, 'NONE', 'none'))
    w.writeframes(struct.pack('<' + 'h'*len(pcm), *pcm))
hexed = ''.join(f'{v & 65535:04x}' for v in pcm)
java = '''package com.dddumpling.game;

/** Yay recreation by Facecam, CC BY 4.0; attribution in assets/AudioCredits.txt.
 * Generated by tools/prepare-survival-cheer.py. */
final class SurvivalCheerRecording {
    private SurvivalCheerRecording() {}
    static short[] build() {
        int size=0;for(String chunk:PCM)size+=chunk.length()/4;
        short[] pcm=new short[size];int at=0;
        for(String chunk:PCM)for(int i=0;i<chunk.length();i+=4)
            pcm[at++]=(short)Integer.parseInt(chunk.substring(i,i+4),16);
        return pcm;
    }
    private static final String[] PCM={
'''
java += ''.join('        "' + hexed[i:i+4000] + '",\n' for i in range(0, len(hexed), 4000))
java += '    };\n}\n'
(root / 'src/com/dddumpling/game/SurvivalCheerRecording.java').write_text(java)
print(f'Cheer: {len(pcm)/22050:.3f}s, peak {max(map(abs, pcm))/32767:.3f}')
